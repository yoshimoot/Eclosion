"""V11.68: split ONE oversized top fragment by a real shared 3D seam.

Input: V11.67 OBJ (10 assembled selectable volumes), generated by
upper_fragment_network.export_obj. No mesh reprojection, no artistic proxy.
Keep the V11.66 lower cradle and the other 8 upper fragments identical.

Usage:
  python refine_upper_cap_obj.py source_v1167.obj output_v1168.obj
"""
from collections import defaultdict
from dataclasses import dataclass
import heapq
import math
from pathlib import Path
import sys

# Physical 3D fracture anchors on the V11.67 large upper cap. The path
# runs on the mesh's existing shared edges rather than a painted line.
START = (-56.8, -84.0, 124.4)
VIA = (-11.1, 7.3, 218.0)
END = (60.5, 45.7, 172.8)
MIN_DAUGHTER_FACES = 1000


@dataclass(frozen=True)
class Part:
    name: str
    vertices: tuple
    faces: tuple


@dataclass(frozen=True)
class SplitResult:
    parts: tuple
    parent: str
    daughter_names: tuple
    seam: tuple
    daughter_outer_faces: tuple


def read_obj(file):
    """Parse the canonical untextured V11.67 OBJ containing disjoint objects."""
    result = []
    vertices = []
    faces = []
    name = None
    preceding = 0
    with Path(file).open(encoding='utf-8') as source:
        source_lines = source.readlines()
    for line in source_lines:
        if line.startswith('o '):
            if name is not None:
                result.append(Part(name, tuple(vertices), tuple(faces)))
                preceding += len(vertices)
            name = line[2:].strip()
            vertices, faces = [], []
        elif line.startswith('v '):
            if name is None:
                raise ValueError('OBJ vertex without an object')
            vertices.append(tuple(float(x) for x in line[2:].split()))
        elif line.startswith('f '):
            if name is None:
                raise ValueError('OBJ face without an object')
            indices = tuple(int(s.split('/')[0])-1-preceding for s in line[2:].split())
            if len(indices)!=3 or min(indices)<0 or max(indices)>=len(vertices):
                raise ValueError('Invalid source OBJ face')
            faces.append(indices)
        elif line.startswith(('vt ', 'vn ', 'l ')):
            raise ValueError('Use the untextured V11.67 geometry OBJ')
    if name is not None:
        result.append(Part(name,tuple(vertices),tuple(faces)))
    if len({obj.name for obj in result})!=len(result):
        raise ValueError('Duplicate OBJ object name')
    return tuple(result)


def write_obj(filename, parts):
    with Path(filename).open('w',encoding='utf-8') as out:
        offset = 0
        for part in parts:
            out.write(f'o {part.name}\ng {part.name}\n')
            for x,y,z in part.vertices:
                out.write(f'v {x:.8f} {y:.8f} {z:.8f}\n')
            for a,b,c in part.faces:
                out.write(f'f {a+1+offset} {b+1+offset} {c+1+offset}\n')
            offset += len(part.vertices)


def _outer_mesh(parent):
    n=len(parent.vertices)//2
    if len(parent.vertices)!=2*n:raise ValueError('Missing inner shell surface')
    ext=[]; inner=[]; walls=[]
    for face in parent.faces:
        if max(face)<n:ext.append(face)
        elif min(face)>=n:inner.append(face)
        else:walls.append(face)
    if len(inner)!=len(ext):raise ValueError('Exterior/interior shell face mismatch')
    for tri,back in zip(ext,inner):
        if back!=tuple(i+n for i in reversed(tri)):
            raise ValueError('Inner shell does not match the exterior')
    edge_faces=defaultdict(list)
    for fi,(a,b,c) in enumerate(ext):
        for u,v in ((a,b),(b,c),(c,a)):
            edge_faces[(min(u,v),max(u,v))].append(fi)
    if any(len(faces)>2 for faces in edge_faces.values()):
        raise ValueError('Nonmanifold source exterior')
    boundary={edge:faces[0] for edge,faces in edge_faces.items() if len(faces)==1}
    return n,ext,inner,walls,edge_faces,boundary


def _nearest(vertices,indices,target):
    return min(indices,key=lambda i: (math.dist(vertices[i],target),i))


def _shortest_path(vertices,neighbors,start,end,forbidden):
    heap=[(0.,start)];dist={start:0.};parent={}
    while heap:
        cost,node=heapq.heappop(heap)
        if cost>dist[node]+1e-9:continue
        if node==end:
            path=[node]
            while path[-1]!=start:path.append(parent[path[-1]])
            return tuple(reversed(path))
        for nxt in sorted(neighbors[node]):
            if nxt in forbidden and nxt!=end:continue
            length=math.dist(vertices[node],vertices[nxt])
            value=cost+length
            if value+1e-9<dist.get(nxt,math.inf):
                dist[nxt]=value;parent[nxt]
                parent[nxt]=node
                heapq.heappush(heap,(value,nxt))
    raise ValueError('No unobstructed fracture route through the parent shell')


def split_cap(parent):
    n,ext,inner,walls,edge_faces,boundary=_outer_mesh(parent)
    source_vertices=parent.vertices
    boundary_vertices={i for a,b in boundary for i in (a,b)}
    a=_nearest(source_vertices,boundary_vertices,START)
    b=_nearest(source_vertices,boundary_vertices,END)
    via=_nearest(source_vertices,range(n),VIA)
    if len({a,b,via})!=3 or via in boundary_vertices:
        raise ValueError('Fracture midpoint lies on source boundary')
    neighbors=defaultdict(set)
    for u,v in edge_faces:
        neighbors[u].add(v);neighbors[v].add(u)
    route1=_shortest_path(source_vertices,neighbors,a,via,boundary_vertices-{a,b})
    route2=_shortest_path(source_vertices,neighbors,via,b,
                          (boundary_vertices-{a,b})|set(route1[:-1]))
    seam=route1+route2[1:]
    cuts={tuple(sorted((u,v))) for u,v in zip(seam,seam[1:])}
    if any(edge not in edge_faces or len(edge_faces[edge])!=2 for edge in cuts):
        raise ValueError('Cut fails to follow true interior material edges')
    face_adjacency=defaultdict(set)
    for edge,owners in edge_faces.items():
        if len(owners)==2 and edge not in cuts:
            x,y=owners;face_adjacency[x].add(y);face_adjacency[y].add(x)
    labels=[-1]*len(ext);groups=[]
    for seed in range(len(ext)):
        if labels[seed]>=0:continue
        label=len(groups);todo=[seed];labels[seed]=label
        for fi in todo:
            for other in face_adjacency[fi]:
                if labels[other]<0:labels[other]=label;todo.append(other)
        groups.append(todo)
    if len(groups)!=2 or min(map(len,groups))<MIN_DAUGHTER_FACES:
        raise ValueError('Split would create more than two pieces or a tiny shard')

    original_walls=defaultdict(list)
    for face in walls:
        pair=tuple(sorted({i%n for i in face}))
        if pair not in boundary:
            raise ValueError('Parent wall does not follow a true perimeter edge')
        original_walls[pair].append(face)
    if any(len(faces)!=2 for faces in original_walls.values()) or set(original_walls)!=set(boundary):
        raise ValueError('Parent perimeter was not completely closed')

    daughters=[]
    for i,group in enumerate(groups):
        outer_faces=[ext[fi] for fi in group]
        faces=outer_faces+[inner[fi] for fi in group]
        for edge,original_fi in boundary.items():
            if labels[original_fi]==i:
                faces.extend(original_walls[edge])  # exact original sidewalls
        for edge in cuts:
            owned=[fi for fi in edge_faces[edge] if labels[fi]==i]
            if len(owned)!=1:raise ValueError('Cut lacks one owner on each side')
            tri=ext[owned[0]]
            u,v=next((u,v) for u,v in ((tri[0],tri[1]),(tri[1],tri[2]),(tri[2],tri[0]))
                     if tuple(sorted((u,v)))==edge)
            if u<v:
                faces.extend(((v,u,v+n),(u,u+n,v+n)))
            else:
                faces.extend(((v,u,u+n),(v,u+n,v+n)))
        ids=sorted({j%n for tri in faces for j in tri})
        remap={j:k for k,j in enumerate(ids)}
        half=len(ids)
        verts=tuple(source_vertices[j] for j in ids)+tuple(source_vertices[j+n] for j in ids)
        mapped=[]
        for face in faces:
            mapped.append(tuple(remap[j] if j<n else remap[j-n]+half for j in face))
        daughters.append(Part(parent.name+('_A' if i==0 else '_B'),verts,tuple(mapped)))
    return tuple(daughters), seam, tuple(len(group) for group in groups)


def refine(parts):
    top=[p for p in parts if p.name.startswith('upper_fragment_')]
    bottom=[p for p in parts if p.name.startswith('lower_cradle_')]
    if len(top)!=9 or len(bottom)!=1 or len(parts)!=10:
        raise ValueError('Expected exactly the ten V11.67 original shell objects')
    cap=max(top,key=lambda obj: len(_outer_mesh(obj)[1]))
    daughters,seam,counts=split_cap(cap)
    output=[]
    for part in parts:
        output.extend(daughters if part is cap else (part,))
    return SplitResult(tuple(output),cap.name,tuple(x.name for x in daughters),seam,counts)


if __name__=='__main__':
    if len(sys.argv)!=3:
        raise SystemExit('Usage: python refine_upper_cap_obj.py input_v1167.obj output_v1168.obj')
    result=refine(read_obj(sys.argv[1]))
    write_obj(sys.argv[2],result.parts)
    print(result.parent,'->',result.daughter_names,
          'outer triangles per daughter:',result.daughter_outer_faces,
          'cut edges:',len(result.seam)-1)
